"""Render every theme in tracks.py to public/audio/music/themes and write
src/data/musicLoops.ts with each file's loop points.

    python tools/music/build.py            # all tracks
    python tools/music/build.py trix lobby # just these
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from tracks import TRACKS  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT_DIR = os.path.join(ROOT, 'public', 'audio', 'music', 'themes')
TS_OUT = os.path.join(ROOT, 'src', 'data', 'musicLoops.ts')


def read_existing() -> dict:
    loops = {}
    if os.path.exists(TS_OUT):
        for line in open(TS_OUT, encoding='utf-8'):
            line = line.strip()
            if line.startswith("'") or (line and line[0].isalpha() and ': {' in line):
                key = line.split(':', 1)[0].strip("' ")
                vals = dict(
                    kv.strip().split(': ')
                    for kv in line.split('{', 1)[1].rstrip('},').split(',')
                    if ': ' in kv
                )
                loops[key] = {k: float(v) for k, v in vals.items()}
    return loops


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    wanted = sys.argv[1:] or list(TRACKS)
    loops = read_existing()
    for name in wanted:
        song = TRACKS[name]()
        info = song.export(os.path.join(OUT_DIR, f'{name}.mp3'))
        loops[name] = {'loopStart': info['loopStart'], 'loopEnd': info['loopEnd']}
        print(f'{name}: {info["seconds"]}s loop')
    loops = {k: loops[k] for k in TRACKS if k in loops}

    lines = [
        '// Generated by tools/music/build.py: loop points (seconds) inside each theme file.',
        '// The file carries wrapped audio around the loop so playback can circle seamlessly.',
        'export const MUSIC_LOOPS: Record<string, { loopStart: number; loopEnd: number }> = {',
    ]
    for k, v in loops.items():
        key = k if k.isidentifier() else f"'{k}'"
        lines.append(f"  {key}: {{ loopStart: {v['loopStart']}, loopEnd: {v['loopEnd']} }},")
    lines.append('};')
    with open(TS_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
